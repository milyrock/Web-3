CREATE TABLE manufacturers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE
);
CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    alias TEXT NOT NULL UNIQUE
);
CREATE TABLE products (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    manufacturer_id BIGINT NOT NULL REFERENCES manufacturers(id),
    category_id BIGINT NOT NULL REFERENCES categories(id),
    name TEXT NOT NULL CHECK(char_length(trim(name)) BETWEEN 2 AND 150),
    alias TEXT NOT NULL UNIQUE,
    short_description TEXT NOT NULL,
    description TEXT NOT NULL,
    price BIGINT NOT NULL CHECK(price BETWEEN 0 AND 100000000),
    image TEXT NOT NULL,
    available BOOLEAN NOT NULL DEFAULT TRUE,
    meta_keywords TEXT NOT NULL DEFAULT '',
    meta_description TEXT NOT NULL DEFAULT '',
    meta_title TEXT NOT NULL DEFAULT ''
);
CREATE TABLE product_properties (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    property_name TEXT NOT NULL,
    property_value TEXT NOT NULL,
    property_price BIGINT NOT NULL DEFAULT 0 CHECK(property_price >= 0)
);
CREATE TABLE product_images (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    image TEXT NOT NULL,
    title TEXT NOT NULL
);
CREATE TABLE feedback (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL CHECK(char_length(trim(name)) BETWEEN 2 AND 100),
    email TEXT NOT NULL,
    subject TEXT NOT NULL CHECK(char_length(trim(subject)) BETWEEN 3 AND 150),
    message TEXT NOT NULL CHECK(char_length(trim(message)) BETWEEN 10 AND 5000),
    rating INTEGER CHECK(rating BETWEEN 1 AND 5),
    status TEXT NOT NULL DEFAULT 'new' CHECK(status IN ('new','in_progress','resolved')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    consent_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX products_category ON products(category_id);
CREATE INDEX properties_product ON product_properties(product_id);
CREATE INDEX images_product ON product_images(product_id);

